#!/usr/bin/env python3
"""Build the SDK protocol bindings from contract/protocol.schema.json.

The schema is generated from crates/gamenight-protocol (a Rust test fails when
it is stale). This script turns it into message type tags, enum values and
protocol constants for every SDK language, so a hand-typed "party_state" can
no longer drift from the daemon:

    python3 scripts/build-protocol.py           # rewrite the bindings
    python3 scripts/build-protocol.py --check   # fail when any is stale

Whole generated files are written outright. Single-file SDKs (gamenight.h,
fake_host.py, studio.js) get a marked block instead, so they stay one file.
--check also scans the hand-written integrations for `"type": "..."` tags the
protocol does not define. Python standard library only.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "contract/protocol.schema.json"
SOURCE = "contract/protocol.schema.json"
BEGIN = "BEGIN GENERATED by scripts/build-protocol.py from " + SOURCE + " (do not edit)"
END = "END GENERATED"


# ---------------------------------------------------------------------------
# Reading the schema
# ---------------------------------------------------------------------------

def snake_upper(name: str) -> str:
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name).upper()


def camel(name: str) -> str:
    head, *rest = name.lower().split("_")
    return head + "".join(part.capitalize() for part in rest)


def messages(schema: dict, side: str) -> dict[str, dict]:
    """Tag -> {"fields": [...], "required": [...]} for one direction."""
    out = {}
    for variant in schema["$defs"][side]["oneOf"]:
        props = variant["properties"]
        tag = props["type"]["const"]
        out[tag] = {
            "fields": sorted(k for k in props if k != "type"),
            "required": sorted(k for k in variant.get("required", []) if k != "type"),
        }
    return out


def enums(schema: dict) -> dict[str, list[str]]:
    """Every string enum, and every enum internally tagged by "kind"."""
    out = {}
    for name, definition in schema["$defs"].items():
        if name in ("ClientMessage", "ServerMessage"):
            continue
        values = list(definition.get("enum", []))
        for variant in definition.get("oneOf", []):
            if "const" in variant:
                values.append(variant["const"])
            values.extend(variant.get("enum", []))
            kind = variant.get("properties", {}).get("kind", {})
            if "const" in kind:
                values.append(kind["const"])
        if values and all(isinstance(v, str) for v in values):
            out[name] = values
    return out


def constants(schema: dict) -> dict[str, object]:
    flat = {}
    for group in schema["x-gamenight-constants"].values():
        flat.update(group)
    return flat


class Protocol:
    def __init__(self, schema: dict):
        self.client = messages(schema, "ClientMessage")
        self.server = messages(schema, "ServerMessage")
        self.tags = sorted(set(self.client) | set(self.server))
        self.enums = enums(schema)
        self.constants = constants(schema)

    def avatar(self) -> dict[str, object]:
        return {k: v for k, v in self.constants.items() if k.startswith("AVATAR_")}


# ---------------------------------------------------------------------------
# Emitters
# ---------------------------------------------------------------------------

def c_literal(value) -> str:
    if isinstance(value, list):
        return "{ " + ", ".join(c_literal(v) for v in value) + " }"
    return json.dumps(value)


def c_block(p: Protocol) -> str:
    lines = ["/* ---- protocol constants -------------------------------------------- */", ""]
    for name, value in p.constants.items():
        if not isinstance(value, list):
            lines.append(f"#define GN_{name} {c_literal(value)}")
    lines += ["", "/* Initialisers, e.g. static const char *colors[] = GN_GUEST_COLORS; */"]
    for name, value in p.constants.items():
        if isinstance(value, list):
            lines.append(f"#define GN_{name} {c_literal(value)}")
    lines += ["", "/* Message \"type\" tags, both directions. */"]
    lines += [f'#define GN_MSG_{t.upper()} "{t}"' for t in p.tags]
    for name, values in p.enums.items():
        lines += ["", f"/* {name} */"]
        lines += [f'#define GN_{snake_upper(name)}_{v.upper()} "{v}"' for v in values]
    return "\n".join(lines)


def gd_literal(value) -> str:
    return json.dumps(value)


def gdscript(p: Protocol) -> str:
    lines = [
        f"## {BEGIN}.",
        "## GameNight wire protocol constants: message tags, enum values, limits.",
        '## Use with `const Protocol := preload("protocol.gd")`.',
        "extends RefCounted",
        "",
    ]
    for name, value in p.constants.items():
        lines.append(f"const {name} := {gd_literal(value)}")
    lines += ["", "## Message \"type\" tags, both directions."]
    lines += [f'const MSG_{t.upper()} := "{t}"' for t in p.tags]
    for name, values in p.enums.items():
        lines += ["", f"## {name}"]
        lines += [f'const {snake_upper(name)}_{v.upper()} := "{v}"' for v in values]
    return "\n".join(lines) + "\n"


def js_module(p: Protocol) -> str:
    def dump(value):
        return json.dumps(value, indent=2)

    lines = [
        f"// {BEGIN}.",
        "// GameNight wire protocol: message tags, their fields, enum values, limits.",
        "// Works as an ES module and as a plain script (sets globalThis.GameNightProtocol).",
        "",
    ]
    for name, value in p.constants.items():
        lines.append(f"export const {name} = {json.dumps(value)};")
    lines += [
        "",
        "/** Message \"type\" tags, both directions. */",
        "export const MSG = Object.freeze(" + dump({t.upper(): t for t in p.tags}) + ");",
        "",
        "/** Client -> host messages: tag -> {fields, required}. */",
        "export const CLIENT_MESSAGES = " + dump(p.client) + ";",
        "",
        "/** Host -> client messages: tag -> {fields, required}. */",
        "export const SERVER_MESSAGES = " + dump(p.server) + ";",
        "",
        "/** String enums by type name. */",
        "export const ENUMS = " + dump(p.enums) + ";",
    ]
    for name, values in p.enums.items():
        members = {v.upper(): v for v in values}
        lines += ["", f"export const {name} = Object.freeze(" + dump(members) + ");"]
    return "\n".join(lines) + "\n"


def js_avatar_block(p: Protocol) -> str:
    return "\n".join(f"    const {k} = {json.dumps(v)};" for k, v in p.avatar().items())


def dart_literal(value) -> str:
    if isinstance(value, list):
        return "[" + ", ".join(dart_literal(v) for v in value) + "]"
    if isinstance(value, str):
        return "'" + value.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"
    return json.dumps(value)


def dart_type(value) -> str:
    if isinstance(value, list):
        return "List<String>"
    return {str: "String", int: "int", float: "double", bool: "bool"}[type(value)]


def dart(p: Protocol) -> str:
    lines = [
        f"// {BEGIN}.",
        "// GameNight wire protocol: message tags, enum values, limits.",
        "",
    ]
    for name, value in p.constants.items():
        lines.append(f"const {dart_type(value)} {camel(name)} = {dart_literal(value)};")
    lines += ["", "/// Message \"type\" tags, both directions."]
    lines += [f"const String msg{camel(t)[0].upper()}{camel(t)[1:]} = '{t}';" for t in p.tags]
    for name, values in p.enums.items():
        lines += ["", f"/// {name}"]
        lines.append(f"const List<String> {name[0].lower()}{name[1:]}Values = {dart_literal(values)};")
    return "\n".join(lines) + "\n"


def py_tags(p: Protocol) -> list[str]:
    return [f'MSG_{t.upper()} = "{t}"' for t in p.tags]


def python(p: Protocol) -> str:
    def dump(value):
        return json.dumps(value, indent=4)

    lines = [
        f'"""{BEGIN}.',
        "",
        "GameNight wire protocol: message tags, their fields, enum values, limits.",
        '"""',
        "",
    ]
    for name, value in p.constants.items():
        lines.append(f"{name} = {json.dumps(value)}")
    lines += ["", "# Message \"type\" tags, both directions."] + py_tags(p)
    for name, values in p.enums.items():
        lines += ["", f"# {name}"]
        lines += [f'{snake_upper(name)}_{v.upper()} = "{v}"' for v in values]
    lines += [
        "",
        "# Client -> host messages: tag -> {fields, required}.",
        "CLIENT_MESSAGES = " + dump(p.client),
        "",
        "# Host -> client messages: tag -> {fields, required}.",
        "SERVER_MESSAGES = " + dump(p.server),
        "",
        "# String enums by type name.",
        "ENUMS = " + dump(p.enums),
    ]
    return "\n".join(lines) + "\n"


def py_fake_host_block(p: Protocol) -> str:
    return "\n".join(
        [f"PROTOCOL_VERSION = {p.constants['PROTOCOL_VERSION']}",
         f"GODOT_SDK_VERSION = {p.constants['GODOT_SDK_VERSION']}"] + py_tags(p)
        + [f'ROLE_{v.upper()} = "{v}"' for v in p.enums["Role"]])


# ---------------------------------------------------------------------------
# Outputs
# ---------------------------------------------------------------------------

# Whole files.
FILES = {
    "sdk/godot/addons/gamenight/protocol.gd": gdscript,
    "sdk/js/protocol.mjs": js_module,
    "mobile/lib/protocol.g.dart": dart,
    "sdk/python/gamenight_protocol.py": python,
}

# Marked blocks inside hand-written files: path -> (comment prefix, suffix, emitter).
BLOCKS = {
    "sdk/c/gamenight.h": ("/* ", " */", c_block),
    "sdk/godot/addons/gamenight/fake_host.py": ("# ", "", py_fake_host_block),
    "web/studio.js": ("    // ", "", js_avatar_block),
}

# Hand-written integrations whose `"type": "..."` literals must be real tags.
SCANNED = [
    "examples/tiny-game.mjs",
    "examples/c-game.c",
    # Files of the pinned ontola/gamenight-mineclonia checkout (see game-sources.json).
    "mineclonia/managed.py",
    "mineclonia/host.py",
    "mineclonia/game_controls.py",
    "scripts/test-love-party.py",
    "sdk/godot/addons/gamenight/gamenight.gd",
    "sdk/godot/addons/gamenight/lobby.gd",
    "sdk/godot/addons/gamenight/screen.gd",
]
TAG_LITERAL = re.compile(r"""\\?["']type\\?["']\s*:\s*\\?["']([a-z_]+)\\?["']""")


def splice(text: str, path: str, prefix: str, suffix: str, body: str) -> str:
    begin, end = f"{prefix}{BEGIN}{suffix}", f"{prefix}{END}{suffix}"
    pattern = re.compile(re.escape(begin) + r"\n.*?" + re.escape(end), re.S)
    if not pattern.search(text):
        raise SystemExit(f"{path}: missing the generated-block markers:\n  {begin}\n  {end}")
    return pattern.sub(lambda _: f"{begin}\n{body}\n{end}", text, count=1)


def scan(p: Protocol) -> list[str]:
    problems = []
    for path in SCANNED:
        if path.startswith("mineclonia/"):
            from game_sources import mineclonia_source
            file = mineclonia_source() / path.removeprefix("mineclonia/")
        else:
            file = ROOT / path
        text = file.read_text(encoding="utf-8")
        for match in TAG_LITERAL.finditer(text):
            if match.group(1) not in p.tags:
                line = text.count("\n", 0, match.start()) + 1
                problems.append(f"{path}:{line}: unknown message type {match.group(1)!r}")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail instead of writing")
    args = parser.parse_args()
    p = Protocol(json.loads(SCHEMA.read_text(encoding="utf-8")))

    wanted = {path: emit(p) for path, emit in FILES.items()}
    for path, (prefix, suffix, emit) in BLOCKS.items():
        current = (ROOT / path).read_text(encoding="utf-8")
        wanted[path] = splice(current, path, prefix, suffix, emit(p))

    stale = []
    for path, text in wanted.items():
        target = ROOT / path
        if target.exists() and target.read_text(encoding="utf-8") == text:
            continue
        stale.append(path)
        if not args.check:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path}")

    problems = scan(p)
    if args.check and stale:
        problems += [f"{path}: stale; run python3 scripts/build-protocol.py" for path in stale]
    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        return 1
    if args.check:
        print(f"protocol bindings match {SOURCE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
